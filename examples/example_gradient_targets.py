"""CPU-only UNsim demand calibration and gradient-target regression demo.

All observations are generated by UNsim before a 200 s forecast anchor. This is
an in-sample engineering example, not a real-data forecast or a learned world
model. See docs/gradient_targets.md for reproducibility and limitations.
"""

import json

import jax
import jax.numpy as jnp
import numpy as np
from jax.example_libraries import optimizers, stax

from unsim import World
from unsim.api import VariableSet
from unsim.gradient_targets import evaluate_objectives, gradient_targets


def build_model():
    world = World(name='',deltat=5,tmax=300,print_mode=0)
    world.addNode('o',0,0)
    world.addNode('d',1,0)
    world.addLink('road','o','d',length=300,free_flow_speed=20,jam_density=.2)
    demand = world.adddemand('o','d',0,200,.22)
    model = world.compile(backend='jax')
    return model,model.parameter(demand,'flow')


def main():
    if any(device.platform != 'cpu' for device in jax.devices()):
        raise RuntimeError('This demonstration must be run with JAX_PLATFORMS=cpu')
    model,ref = build_model()
    vset = VariableSet(model,[ref])
    initial = np.array([[.18],[.25],[.42],[.31]],dtype=np.float32)
    truth = np.array([.36,.32,.28,.38],dtype=np.float32)
    observations = []
    for value in truth:
        params = vset.inject(jnp.array([value]),model.raw.params)
        sim = model.raw.simulate(params,model.raw.config,differentiable=False)
        observations.append(jax.lax.stop_gradient(sim.cum_departure[0,30]))
    observations = jnp.stack(observations)  # 150 s, strictly before 200 s anchor
    objectives = [model.objective(lambda r,y=y:(r.link('road').cum_departure()[30]-y)**2)
                  for y in observations]
    before,raw_gradient = evaluate_objectives(model,[ref],objectives,initial)
    batch = gradient_targets(initial,raw_gradient,[.05],[.65],delta=.05,kappa=3.)
    teacher_value,_ = evaluate_objectives(model,[ref],objectives,batch.targets)

    # An explicit optimizer control must equal the projected teacher update:
    # JAX's SGD applies the same step to the same already-clipped gradient.
    normalized_initial = (jnp.asarray(initial)-.05)/.6
    init_sgd,update_sgd,get_sgd = optimizers.sgd(float(batch.step_multiplier))
    state = init_sgd(normalized_initial)
    state = update_sgd(0,batch.clipped_gradients,state)
    direct = jnp.clip(get_sgd(state),0.,1.)
    direct_error = float(jnp.max(jnp.abs(direct-batch.normalized_targets)))

    # Regression gets only current demand estimate and the 150 s observation;
    # it never receives the synthetic future flow or the true demand value.
    inputs = jnp.stack((normalized_initial[:,0],observations/100.),axis=-1)
    init_net,apply_net = stax.serial(stax.Dense(8),stax.Tanh,stax.Dense(1),stax.Sigmoid)
    _,params = init_net(jax.random.PRNGKey(2026),inputs.shape)
    init_opt,update_opt,get_opt = optimizers.adam(.03)
    opt_state = init_opt(params)
    targets = jax.lax.stop_gradient(batch.normalized_targets)
    objective = lambda p:jnp.mean((apply_net(p,inputs)-targets)**2)
    value_grad = jax.jit(jax.value_and_grad(objective))
    initial_regression_error = float(objective(params))
    for step in range(250):
        _,grad = value_grad(get_opt(opt_state))
        opt_state = update_opt(step,grad,opt_state)
    params = get_opt(opt_state)
    predicted_norm = apply_net(params,inputs)
    predicted = .05+.6*predicted_norm
    regression_value,_ = evaluate_objectives(model,[ref],objectives,predicted)

    report = {
        'device':'cpu','batch':len(initial),'network':'one fixed link',
        'observed_cumulative_time_seconds':150,'forecast_anchor_seconds':200,
        'source':'synthetic in-sample UNsim; no real future observation',
        'initial_demands':initial[:,0].tolist(),
        'synthetic_observations':np.asarray(observations).tolist(),
        'objective_before':np.asarray(before).tolist(),
        'raw_gradient':np.asarray(raw_gradient)[:,0].tolist(),
        'target_demands':np.asarray(batch.targets)[:,0].tolist(),
        'objective_after_target':np.asarray(teacher_value).tolist(),
        'direct_sgd_max_normalized_target_error':direct_error,
        'regressor_parameter_count':sum(np.asarray(x).size for x in jax.tree.leaves(params)),
        'regression_steps':250,'regression_mse_initial':initial_regression_error,
        'regression_mse_final':float(objective(params)),
        'regressed_demands':np.asarray(predicted)[:,0].tolist(),
        'objective_after_regression':np.asarray(regression_value).tolist(),
    }
    print(json.dumps(report,indent=2,allow_nan=False))


if __name__ == '__main__':
    main()
